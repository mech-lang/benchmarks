local g = {}
require 'c-gmp'(g, {})
local bn = require 'bn'
local function z(n) return g.mpz_init_set_d(n) end
local function value(x, expected) assert(tostring(x) == tostring(expected), tostring(x)) end
local a = z(-7)
local b = z(3)
local out = z(0)
value(g.mpz_tdiv_q(a, b, out), -2)
value(g.mpz_fdiv_q(a, b, out), -3)
value(g.mpz_tdiv_q(a, b, a), -2)
value(g.mpz_fdiv_q(z(-7), b, b), -3)
value(g.mpz_tdiv_q(z(7), z(-3), out), -2)
value(g.mpz_fdiv_q(z(7), z(-3), out), -3)
value(g.mpz_tdiv_q(z(-7), z(-3), out), 2)
value(g.mpz_fdiv_q(z(-7), z(-3), out), 2)
local alias = z(7)
value(g.mpz_tdiv_q(alias, alias, alias), 1)
value(g.mpz_mul_si(z(123), -4, out), -492)
value(g.mpz_mul_ui(z(123), 4, out), 492)
value(g.mpz_add(z(-492), out, out), 0)
value(g.mpz_set(out, z(23)), 23)
value(g.mpz_addmul_ui(out, out, 4), 115)
value(g.mpz_submul_ui(out, out, 2), -115)
local huge = bn.number('1267650600228229401496703205376')
local two = bn.number(2)
value(bn.mul(huge, two), '2535301200456458802993406410752')
value(bn.add(huge, bn.number(1)), '1267650600228229401496703205377')
value(bn.sub(huge, bn.number(1)), '1267650600228229401496703205375')
value(bn.div(bn.number(-7), bn.number(3)), -2)
value(bn.number(math.maxinteger), '9223372036854775807')
value(bn.number(math.mininteger), '-9223372036854775808')
assert(bn.tonumber(bn.number(math.maxinteger)) == math.maxinteger)
assert(bn.tonumber(bn.number(math.mininteger)) == math.mininteger)
assert(math.type(bn.tonumber(huge)) == 'float')
assert(bn.tonumber(huge) == 2^100)
value(z(3.8), 3)
value(z(-3.8), -3)
assert(bn.number(2) < bn.number(3))
assert(bn.number(2) <= bn.number(2))
assert(bn.number(2) == bn.number(2))
assert(bn.tonumber(bn.number(7)) == 7)
assert(math.type(bn.tonumber(bn.number(7))) == 'integer')
assert(g.mpz_get_d(z(-7)) == -7)
assert(not pcall(g.mpz_tdiv_q, z(1), z(0), out))
assert(not pcall(g.mpz_fdiv_q, z(1), z(0), out))
assert(not pcall(bn.div, bn.number(1), bn.number(0)))
assert(not pcall(g.mpz_mul_ui, z(1), -1, out))
assert(not pcall(g.mpz_mul_si, z(1), 0.5, out))
assert(not pcall(g.mpz_set, {}, out))
assert(not pcall(bn.number, 'invalid'))
assert(not pcall(g.mpz_init_set_d, 0/0))
assert(not pcall(g.mpz_init_set_d, math.huge))
local retired = z(9)
getmetatable(retired).__gc(retired)
getmetatable(retired).__gc(retired)
assert(not pcall(g.mpz_get_d, retired))
for i = 1, 10000 do local cell = z(i) end
collectgarbage('collect')
io.write('general mpz tests passed\n')
