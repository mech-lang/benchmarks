import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

P = Path(__file__).with_name('typescript_single_entry.py')
S = importlib.util.spec_from_file_location('tested_typescript_single', P)
m = importlib.util.module_from_spec(S); S.loader.exec_module(m)
T = importlib.util.spec_from_file_location('typescript_bounded_fixtures', P.with_name('test_typescript_bounded.py'))
t = importlib.util.module_from_spec(T); T.loader.exec_module(t)


class CaptureTests(unittest.TestCase):
    def fixture(self, directory):
        args = t.TypeScriptBounded().receipt_fixture(directory)
        for name in ('start', 'active', 'process'):
            path = directory/(name+'.json'); value = json.loads(path.read_bytes())
            value.update(kind='typescript-single-entry', stdin_bytes=0, stdin_sha256=hashlib.sha256(b'').hexdigest(),
                process_timeout_seconds=m.kb.TIMEOUT, native_file_limit_bytes=m.kb.FILE_LIMIT,
                stdout_capture_limit_bytes=m.kb.FILE_LIMIT+m.kb.PIPE_CHUNK,
                maximum_process_group_rss_bytes=m.kb.RSS_LIMIT)
            path.write_text(json.dumps(value))
        return args[0], args[1], args[3]

    def bytecode(self, benchmark):
        name = 'mainThread' if benchmark == 'binarytrees' else 'calculatePi'
        return ('[generated bytecode for function: '+name+' (0x42 <SharedFunctionInfo '+name+'>)]\n'
                'Bytecode length: 10\nHandler Table (size = 0)\nSource Position Table (size = 2)\n'
                '0x22 <TrustedByteArray[2]>\n').encode()

    def test_separate_observer_policy(self):
        self.assertEqual((m.b.kb.TIMEOUT,m.b.kb.FILE_LIMIT,m.b.kb.RSS_LIMIT),(30,8*1024**2,2*1024**3))
        self.assertEqual((m.kb.TIMEOUT,m.kb.FILE_LIMIT,m.kb.RSS_LIMIT),(180,128*1024**2,10*1024**3))
        self.assertIsNot(m.kb,m.b.kb)

    def test_direct_unchanged_main_and_no_execution_policy_override(self):
        plan={'compiled':{'node':'/node','profiles':[{'benchmark':b,'javascript':{'path':'/'+b+'.js'}} for b in m.INPUTS]}}
        for bench,n in m.INPUTS.items():
            cmd=m.command(plan,{'kind':'subject','benchmark':bench})
            self.assertEqual(cmd[0],'/node');self.assertEqual(cmd[-2:],['/'+bench+'.js',str(n)])
            self.assertFalse(any('jitless' in x or 'always-turbofan' in x or 'max-old-space' in x or x in ('--eval','--require') for x in cmd))
            self.assertNotIn('--log-code-disassemble',cmd);self.assertNotIn('--print-code',cmd)
            self.assertIn('--redirect-code-traces',cmd)
            self.assertFalse(any(x.startswith('--redirect-code-traces-to=') or x=='--no-logfile-per-isolate' for x in cmd))
        self.assertEqual(m.command(plan,{'kind':'capabilities'}),['/node','--v8-options'])

    def test_complete_frozen_output_oracles(self):
        for b in m.INPUTS:
            raw=m.expected_output(b);self.assertEqual((len(raw),hashlib.sha256(raw).hexdigest()),m.OUTPUTS[b])

    def test_actual_closed_prerequisite_shapes_without_runtime_hashes(self):
        original=m.b.sha
        def small_only(path):
            p=Path(path)
            self.assertTrue(p.is_relative_to(m.ROOT), 'Runtime hash attempted by saved-evidence replay')
            self.assertLess(p.stat().st_size,2*1024**2)
            return original(p)
        with patch.object(m.b,'sha',small_only):
            pins={};compiled=m.prerequisites(pins)
        self.assertEqual(len(compiled['profiles']),10)
        self.assertEqual(pins[str(m.STATIC_REVIEW)],m.STATIC_SHA)
        self.assertIn(str(m.PRIOR/'run-v1/terminal.json'),pins)

    def test_capability_flags_required(self):
        names={x.split('=')[0].removeprefix('--no-').removeprefix('--') for b in m.INPUTS for x in m.diagnostic_options(b)}
        raw=''.join('  --'+n+' (description)\n' for n in names).encode()
        self.assertEqual(set(m.capabilities(raw)['required_options']),names)
        with self.assertRaises(AssertionError):m.capabilities(raw.replace(b'--print-opt-code (',b'--other ('))

    def test_bytecode_gc_and_exact_full_stdout_retained(self):
        gc=b'[42:0xab]       19 ms: Scavenge 10.1 (12.2) -> 9.1 (12.2) MB, pooled: 0 MB, 0.12 / 0.00 ms  (average mu = 1.000, current mu = 1.000) allocation failure; \n'
        for bench in m.INPUTS:
            expected=m.expected_output(bench);prefix=self.bytecode(bench)
            split=m.split_stdout(prefix+gc+expected+gc,bench,42)
            self.assertEqual(split,dict(bytecode=prefix,gc=gc+gc,subject=expected))
            for raw in (prefix+expected+b'warning\n',b'warning\n'+prefix+expected,prefix+expected[:-1],prefix+prefix+expected):
                with self.assertRaises(AssertionError):m.split_stdout(raw,bench,42)

    def test_unknown_gc_and_wrong_outer_function_rejected(self):
        raw=self.bytecode('binarytrees')+b'[42:0xab] 0 ms: unknown collector\n'+m.expected_output('binarytrees')
        with self.assertRaises(AssertionError):m.split_stdout(raw,'binarytrees',42)
        with self.assertRaises(AssertionError):m.split_stdout(self.bytecode('pidigits')+m.expected_output('binarytrees'),'binarytrees',42)

    def test_normal_owned_receipt(self):
        with tempfile.TemporaryDirectory() as tmp:
            p=Path(tmp);args=self.fixture(p);receipt,stdout,stderr=m.native_receipt(p,*args)
            self.assertEqual(receipt['pid'],42);self.assertEqual(stdout,b'');self.assertEqual(stderr,b'')

    def test_lifecycle_and_policy_faults_rejected(self):
        mutations=[lambda x:x.update(direct_child_reaped=False),lambda x:x.update(remaining_process_group=[43]),
            lambda x:x.update(exit_status=-15),lambda x:x.update(process_timeout_seconds=30),
            lambda x:x.update(cleanup_errors=['bad']),lambda x:x['identity'].update(ppid=1),
            lambda x:x['leader_identity_before_reap'].update(birth_microseconds=4)]
        for change in mutations:
            with self.subTest(change=change),tempfile.TemporaryDirectory() as tmp:
                p=Path(tmp);args=self.fixture(p);v=json.loads((p/'process.json').read_bytes());change(v)
                (p/'process.json').write_text(json.dumps(v))
                with self.assertRaises(AssertionError):m.native_receipt(p,*args)

    def test_raw_output_mutation_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            p=Path(tmp);args=self.fixture(p);(p/'stdout.bin').write_bytes(b'changed')
            with self.assertRaises(AssertionError):m.native_receipt(p,*args)

    def test_inventory_rejects_links_and_oversized_files(self):
        with tempfile.TemporaryDirectory() as tmp:
            p=Path(tmp);(p/'x').write_bytes(b'abc');self.assertEqual(m.inventory(p)['x']['bytes'],3)
            (p/'link').symlink_to(p/'x')
            with self.assertRaises(AssertionError):m.inventory(p)
            (p/'link').unlink()
            with patch.object(m.kb,'FILE_LIMIT',0),patch.object(m.kb,'PIPE_CHUNK',0):
                with self.assertRaises(AssertionError):m.inventory(p)

    def test_failed_stage_retains_closed_terminal_without_admission(self):
        with tempfile.TemporaryDirectory() as tmp:
            directory=Path(tmp)
            report=dict(status='failed',native_processes_started=0,registered_commands=[],captures=[],
                        validated_artifacts={},active=None,required_work_qualified=False)
            with patch.object(m.b,'verify'),patch.object(m.kb.kh,'verify_lock'):
                m.finish(report,{'schedule':[]},directory,{},object())
            terminal=json.loads((directory/'terminal.json').read_bytes())
            self.assertEqual(terminal['status'],'failed');self.assertEqual(terminal['integrity_errors'],[])
            self.assertFalse(terminal['required_work_qualified']);self.assertFalse(terminal['full_timings_qualified'])
            self.assertEqual(terminal['report_sha256'],m.sha(directory/'report.json'))

    def test_final_inventory_cannot_adopt_changed_validated_artifact(self):
        with tempfile.TemporaryDirectory() as tmp:
            directory=Path(tmp);(directory/'case').mkdir();(directory/'case/x').write_bytes(b'old')
            snapshot=m.inventory(directory/'case');(directory/'case/x').write_bytes(b'changed')
            report=dict(status='failed',native_processes_started=0,registered_commands=[],captures=[],
                        validated_artifacts={'case':snapshot},active=None)
            with patch.object(m.b,'verify'),patch.object(m.kb.kh,'verify_lock'):
                m.finish(report,{'schedule':[]},directory,{},object())
            terminal=json.loads((directory/'terminal.json').read_bytes())
            self.assertEqual(terminal['status'],'failed-integrity')
            self.assertTrue(any('Validated artifact changed' in x for x in terminal['integrity_errors']))

    def test_missing_registered_process_receipt_fails_finalization(self):
        with tempfile.TemporaryDirectory() as tmp:
            directory=Path(tmp);report=dict(status='failed',native_processes_started=1,
                registered_commands=[{'directory':'01-binarytrees','pid':42}],captures=[],
                validated_artifacts={},active={'pid':42})
            with patch.object(m.b,'verify'),patch.object(m.kb.kh,'verify_lock'):
                m.finish(report,{'schedule':[]},directory,{},object())
            terminal=json.loads((directory/'terminal.json').read_bytes())
            self.assertEqual(terminal['status'],'failed-integrity')
            self.assertTrue(any('receipt inventory' in x for x in terminal['integrity_errors']))


