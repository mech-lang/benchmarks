"""Lossless partition of retained Node 24.19 V8 diagnostics and exact application output.

No source evaluation or native invocation. Unknown diagnostic rows fail closed.
The grammar covers the retained Ignition/Maglev bytecode, feedback and GC forms;
it is intentionally not a permissive general-purpose V8 log filter.
"""
import hashlib
import re


def require(value,message):
    if not value:raise AssertionError(message)


def digest(data):return hashlib.sha256(data).hexdigest()


HEADER = re.compile(rb'(?:\[generated bytecode for function: ([A-Za-z_$][\w$]*) \(0x[0-9a-f]+ <SharedFunctionInfo \1>\)\]|Compiling 0x[0-9a-f]+ <JSFunction [A-Za-z_$][\w$]* \(sfi = 0x[0-9a-f]+\)> with Maglev|== Inlining 0x[0-9a-f]+ <SharedFunctionInfo [A-Za-z_$][\w$]*>)\n')
BODY = [re.compile(p+rb'\n') for p in (
    rb'Bytecode length: [1-9][0-9]*',
    rb'(?:Parameter count|Register count|Frame size) [0-9]+',
    rb'\s*(?:[0-9]+ [SE]> )?0x[0-9a-f]+ @\s+[0-9]+ : (?:[0-9a-f]{2} )+\s*[A-Za-z][A-Za-z0-9.]+(?: [^\r\n]*)?',
    rb'(?:Constant pool|Handler Table|Source Position Table) \(size = [0-9]+\)',
    rb'0x[0-9a-f]+: \[(?:TrustedFixedArray|FeedbackVector)\]',
    rb'0x[0-9a-f]+ <Other heap object \(TRUSTED_BYTE_ARRAY_TYPE\)>',
    rb' - map: 0x[0-9a-f]+ <Map\([A-Z_]+\)>',
    rb' - (?:length|tiering_in_progress|osr_tiering_in_progress|invocation count): [0-9]+',
    rb' - shared function info: 0x[0-9a-f]+ <SharedFunctionInfo [A-Za-z_$][\w$]*>',
    rb' - closure feedback cell array: 0x[0-9a-f]+: \[ClosureFeedbackCellArray\](?: in ReadOnlySpace)?',
    rb' - elements:',
    rb'\s+[0-9]+: (?:0x[0-9a-f]+ <[^\r\n]+>|[0-9]+)',
    rb' - slot #[0-9]+ [A-Za-z][A-Za-z0-9]*(?: [A-Za-z0-9_:]+)*(?: \{)?',
    rb'\s+\[[0-9]+\]: (?:[0-9]+|\[cleared\]|0x[0-9a-f]+ <[^\r\n]+>|\[weak\] 0x[0-9a-f]+ <[^\r\n]+>)',
    rb'\s+(?:\[weak\] )?0x[0-9a-f]+ <Map\[[0-9]+\]\([A-Z_]+\)>: (?:LoadHandler\(Smi\)\(kind = kField, is in object = [01], is double = [01], field index = [0-9]+\) \{|StoreHandler\(field transition to 0x[0-9a-f]+ <Map\[[0-9]+\]\([A-Z_]+\)>\))',
    rb'\s*[{}]',rb'',
)]
NOTICE=b'Concurrent maglev has been disabled for tracing.\n'
SUFFIX=re.compile(rb'\) \(opt id ([0-9]+)\) for deoptimization, reason: (dependent field type changed)\]\n')
PREFIX=re.compile(rb'\[marking dependent code (0x[0-9a-f]+) <Code (TURBOFAN_JS|MAGLEV)> \(0x[0-9a-f]+ <SharedFunctionInfo ([A-Za-z_$][\w$]*)>')


def split(raw,expected,pid,outer_name,code=b''):
    require(type(pid) is int and pid>0,'Positive native PID required')
    require(raw.endswith(b'\n') and expected.endswith(b'\n'),'Truncated raw or expected stream')
    expected_lines=expected.splitlines(keepends=True);next_line=0;offset=0;segments=[];parts={}
    gc=re.compile(rb'\['+str(pid).encode()+rb':0x[0-9a-fA-F]+\]\s+\d+ ms: '
        rb'(?:Scavenge|Mark-Compact|Minor Mark-Sweep)(?: \([^\r\n]*\))* '
        rb'\d+\.\d+ \(\d+\.\d+\) -> \d+\.\d+ \(\d+\.\d+\) MB, '
        rb'pooled: \d+ MB, \d+\.\d+ / \d+\.\d+ ms [^\r\n]*'
        rb'\(average mu = \d+\.\d+, current mu = \d+\.\d+\) [^\r\n]*; [^\r\n]*\n')
    generated=0;blocks=[];block=None;notice=0;suffixes=[]
    def complete():
        if block is not None:
            require(all(block[k] for k in ('parameters','registers','frame','instructions','constant_pool','handlers','positions','position_table')), 'Incomplete native bytecode block')
    for line_no,line in enumerate(raw.splitlines(keepends=True),1):
        head=HEADER.fullmatch(line);suffix=SUFFIX.fullmatch(line)
        if next_line<len(expected_lines) and line==expected_lines[next_line]:
            complete();category='application';next_line+=1
        elif gc.fullmatch(line):category='gc'
        elif line==NOTICE:
            require(offset==0 and notice==0,'Unexpected or repeated Maglev notice');notice+=1;category='notice'
        elif head:
            complete()
            if head[1] is not None:
                require(head[1]==outer_name.encode(),'Unexpected generated outer bytecode');generated+=1
            block=dict(start=offset,line=line_no,header=line.decode().rstrip(),parameters=False,registers=False,frame=False,
                       instructions=False,constant_pool=False,handlers=False,positions=False,position_table=False)
            blocks.append(block);category='bytecode'
        elif suffix:
            complete();require(next_line==len(expected_lines),'Deoptimization suffix interrupts application output')
            suffixes.append(int(suffix[1]));category='deoptimization-suffix'
        elif block is not None and any(p.fullmatch(line) for p in BODY):
            category='bytecode'
            for key,prefix in [('parameters',b'Parameter count '),('registers',b'Register count '),('frame',b'Frame size '),
                ('constant_pool',b'Constant pool '),('handlers',b'Handler Table '),('positions',b'Source Position Table ')]:
                if line.startswith(prefix):block[key]=True
            if b' @ ' in line:block['instructions']=True
            if re.fullmatch(rb'0x[0-9a-f]+ <Other heap object \(TRUSTED_BYTE_ARRAY_TYPE\)>\n',line):block['position_table']=True
        else:raise AssertionError('Unrecognized stdout row '+str(line_no)+' at byte '+str(offset)+': '+repr(line[:160]))
        if segments and segments[-1]['category']==category:segments[-1]['end']=offset+len(line)
        else:segments.append(dict(category=category,start=offset,end=offset+len(line)))
        parts.setdefault(category,[]).append(line);offset+=len(line)
    complete();require(next_line==len(expected_lines) and generated==1,'Missing application lines or outer bytecode')
    prefixes=list(PREFIX.finditer(code))
    require(len(prefixes)==len(suffixes),'Split deoptimization prefix/suffix count differs')
    deopt=[]
    for prefix,opt_id in zip(prefixes,suffixes):
        # Each code object's native header binds its optimization ID; the stdout
        # suffix originates in Deoptimizer::TraceMarkForDeoptimization (862-869).
        target=re.compile(rb'optimization_id = '+str(opt_id).encode()+rb'\n(?:(?!---).)*?\nname = '+re.escape(prefix[3])+rb'\n(?:(?!---).)*?\naddress = '+re.escape(prefix[1])+rb'\n',re.S)
        if prefix[2]==b'TURBOFAN_JS':
            require(target.search(code),'Split deoptimization ID/name/code address is unbound')
        else:
            require(re.search(rb'kind = MAGLEV\nname = '+re.escape(prefix[3])+rb'\ncompiler = maglev\naddress = '+re.escape(prefix[1])+rb'\n',code),'Split Maglev deoptimization name/code address is unbound')
        deopt.append(dict(optimization_id=opt_id,optimization_id_header_verified=prefix[2]==b'TURBOFAN_JS',function=prefix[3].decode(),code_address=prefix[1].decode(),code_prefix_start=prefix.start(),code_prefix_end=prefix.end()))
    joined={k:b''.join(v) for k,v in parts.items()};require(joined['application']==expected,'Application bytes differ')
    for segment in segments:segment['sha256']=digest(raw[segment['start']:segment['end']])
    require(segments[0]['start']==0 and segments[-1]['end']==len(raw) and
        all(a['end']==b['start'] for a,b in zip(segments,segments[1:])), 'Partition has gaps or overlap')
    return dict(raw_bytes=len(raw),raw_sha256=digest(raw),application_bytes=len(expected),application_sha256=digest(expected),
        application_lines=next_line,complete_application_output=True,lossless_partition=True,segments=segments,
        streams={k:dict(bytes=len(v),sha256=digest(v),lines=len(v.splitlines())) for k,v in joined.items()},
        bytecode_blocks=blocks,split_deoptimization_records=deopt,required_work_qualified=False,benchmark_samples=0,chart_admission=False)
